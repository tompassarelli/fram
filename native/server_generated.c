typedef struct generated_owner {
  _Atomic size_t references;
  native_arena arena;
  native_capability capability;
} generated_owner;

typedef struct generated_store_generation {
  _Atomic size_t references;
  generated_owner *owner;
  struct generated_store_generation *parent;
  fram_server_store_boot_return result;
  size_t chain_reserved_bytes;
  size_t chain_generations;
} generated_store_generation;

