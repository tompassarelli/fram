#define FRAM_SERVER_ADAPTER_ABI 1u
#define FRAM_SERVER_ARENA_BASE_BYTES ((size_t)(64u * 1024u * 1024u))
#define FRAM_SERVER_CAPABILITY_TOKEN UINT64_C(1)
#define FRAM_SERVER_FRAME_HEADER_BYTES ((size_t)26u)
#define FRAM_SERVER_FRAME_BODY_LENGTH_OFFSET ((size_t)14u)
#define FRAM_SERVER_FRAME_MAX_BODY_BYTES UINT32_C(1048576)
#define FRAM_SERVER_FRAME_MAX_BYTES ((size_t)1048602u)
#define FRAM_SERVER_IO_CHUNK_BYTES ((size_t)8192u)

